from __future__ import annotations

from collections.abc import Callable
from typing import Any, Protocol, runtime_checkable

from robot_dispatch.db.models import OutboxMessage, Robot, Task, TaskEvent


@runtime_checkable
class TaskRepository(Protocol):
    async def add(self, task: Task) -> Task: ...
    async def get(self, task_id: Any) -> Task | None: ...
    async def get_by_external_id(self, external_id: str) -> Task | None: ...
    async def lock_ready(self, *, now: Any, limit: int) -> list[Task]: ...
    async def lock_expired_leases(self, *, now: Any, limit: int) -> list[Task]: ...
    async def list(
        self,
        *,
        statuses: list[str] | None = None,
        robot_id: Any | None = None,
        task_type: str | None = None,
        limit: int = 50,
        offset: int = 0,
    ) -> list[Task]: ...
    async def count_by_status(self) -> dict[str, int]: ...


@runtime_checkable
class RobotRepository(Protocol):
    async def add(self, robot: Robot) -> Robot: ...
    async def get(self, robot_id: Any) -> Robot | None: ...
    async def get_by_name(self, name: str) -> Robot | None: ...
    async def list(self) -> list[Robot]: ...
    async def find_idle_for(self, *, task_type: str, now: Any, offline_after: int) -> Robot | None: ...


@runtime_checkable
class EventRepository(Protocol):
    async def add(self, event: TaskEvent) -> TaskEvent: ...
    async def list_for_task(self, task_id: Any, *, limit: int = 200) -> list[TaskEvent]: ...


@runtime_checkable
class OutboxRepository(Protocol):
    async def add(self, message: OutboxMessage) -> OutboxMessage: ...
    async def lock_pending(self, *, now: Any, limit: int) -> list[OutboxMessage]: ...
    async def mark_sent(self, message: OutboxMessage, sent_at: Any) -> None: ...
    async def mark_failed(
        self, message: OutboxMessage, error: str, available_at: Any, attempts: int
    ) -> None: ...


@runtime_checkable
class UnitOfWork(Protocol):
    tasks: TaskRepository
    robots: RobotRepository
    events: EventRepository
    outbox: OutboxRepository

    async def __aenter__(self) -> UnitOfWork: ...
    async def __aexit__(self, exc_type: Any, exc: Any, tb: Any) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...


UnitOfWorkFactory = Callable[[], UnitOfWork]
